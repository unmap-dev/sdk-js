/**
 * Renders `docs/optimize/spec.md` from the field table. `scripts/gen-spec.mjs` writes it, and a
 * test fails when the committed file differs from what this returns.
 */

import { FIELD_STATUSES, FIELDS, MAX_LOAD_TYPES, type FieldRow, type FieldStatus } from "./fields";

const STATUS_LABEL: Record<FieldStatus, string> = {
  supported: "supported",
  ignored: "ignored",
  rejected: "rejected",
  "planned-v2": "planned (V2)",
  "planned-v3": "planned (V3)",
};

const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

const code = (text: string | number | boolean): string => `\`${String(text)}\``;

function typeText(row: FieldRow): string {
  const base = row.type === "any" ? "message" : row.type;
  if (row.repeated) return `${base}[]`;
  if (row.map) return `map<string, ${base}>`;
  return base;
}

/** The behaviour column: what Unmap does when the field is sent. */
export function behaviourOf(row: FieldRow): string {
  const parts = [row.description, `Type ${code(typeText(row))}.`];
  if (row.default !== undefined) parts.push(`Default ${code(row.default)}.`);
  if (row.enumValues && row.status === "supported") {
    const groups = new Map<FieldStatus, string[]>();
    for (const v of row.enumValues) groups.set(v.status, [...(groups.get(v.status) ?? []), code(v.value)]);
    parts.push(
      `Values: ${[...groups].map(([status, names]) => `${names.join(", ")} ${status === "supported" ? "supported" : `refused, ${STATUS_LABEL[status]}`}`).join("; ")}.`,
    );
  }
  if (row.maxItems) parts.push(`More than ${row.maxItems.max}: error ${code(row.maxItems.code)}, "${row.maxItems.message}"`);
  if (row.required) parts.push("Required.");
  if (row.requiredWhen) parts.push(`Required when ${code(row.requiredWhen.field)} is ${code(row.requiredWhen.equals)}: error ${code("MISSING_REQUIRED_FIELD")}.`);
  if (row.status === "ignored") parts.push(`Warning ${code(row.code ?? "")} when set: "${row.message}"`);
  if (row.status === "rejected" || row.status.startsWith("planned")) {
    const when = row.status === "rejected" ? "when set" : "when set to a non-default value";
    parts.push(`Error ${code(row.code ?? "")} ${when}: "${row.message}"`);
    if (row.hint) parts.push(`Hint: ${row.hint}`);
  }
  if (row.rationale) parts.push(row.rationale);
  return parts.join(" ");
}

export function renderSpec(): string {
  const counts = FIELD_STATUSES.map((status) => `${FIELDS.filter((row) => row.status === status).length} ${STATUS_LABEL[status]}`);
  const lines = [
    "# Unmap Optimize: GMPRO field support",
    "",
    "<!-- Generated by packages/optimize-schema/scripts/gen-spec.mjs from packages/optimize-schema/src/fields.ts. Do not edit by hand: change the table, then run `pnpm --filter @unmap/optimize-schema gen-spec`. -->",
    "",
    "Every field of a Google Maps Platform Route Optimization (GMPRO) `OptimizeToursRequest`, and what Unmap Optimize does with it.",
    "Field names and structure follow the public GMPRO REST reference (v1); the descriptions are Unmap's own wording.",
    "",
    `The table has ${FIELDS.length} rows: ${counts.join(", ")}.`,
    "",
    "- **supported**: honoured.",
    "- **ignored**: accepted with no effect. A non-default value adds a `FIELD_IGNORED` warning (one per field, with a count), never an error.",
    "- **rejected**: refused with the error shown. Unmap does not plan to support it.",
    "- **planned (V2 / V3)**: refused with `FIELD_NOT_SUPPORTED_YET` when set to anything but its default, because dropping a constraint silently would return a plan the caller did not ask for. Sent at its default (`false`, `0`, `\"0s\"`, `[]`, `{}`, an `_UNSPECIFIED` enum, or the default shown), it is accepted.",
    "",
    "How to read a path: `name[]` is an element of an array, `name{}` is a value of a map whose keys are yours (load type names). Rows under a refused or ignored field are not listed: nothing below it is read.",
    "",
    "Rules that apply to the whole body:",
    "",
    "- Field names may be camelCase or snake_case. Sending both spellings of one field in the same object is a `CONFLICTING_FIELD_NAMES` error. Map keys (load type names) and string values are never rewritten.",
    "- A field that is not in this table is an `UNKNOWN_FIELD` error, so a typo never silently drops a constraint.",
    "- Durations are strings such as `\"300s\"` or `\"1.5s\"`. Timestamps are RFC 3339 strings or `{ \"seconds\": ..., \"nanos\": ... }`. 64-bit integers may be decimal strings or JSON integers up to 2^53 - 1.",
    "- Errors stop at `maxValidationErrors` (default 100, capped at 10,000).",
    `- At most ${MAX_LOAD_TYPES} distinct load type names per request, counted over every \`loadDemands\` and \`loadLimits\` key in the model. The first name past that is an \`OUT_OF_RANGE\` error. Each load type is a solver dimension on every stop and vehicle, so the cap bounds the model the solver builds.`,
    "- No field of this request takes a URI, so nothing in it is checked for `gs://`. The batch methods that read Cloud Storage URIs are not available (their paths answer `404`); `GCS_URI_NOT_SUPPORTED` is reserved for them and nothing returns it in V1.",
    "",
    "| Field path | Status | Behaviour |",
    "| --- | --- | --- |",
    ...FIELDS.map((row) => `| ${code(row.path)} | ${STATUS_LABEL[row.status]} | ${cell(behaviourOf(row))} |`),
    "",
  ];
  return lines.join("\n");
}
